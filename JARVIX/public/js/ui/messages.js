/* JARVIX — message list rendering: bubbles, streaming updates, code-block actions, flashcards, quizzes, scrolling. */
(function () {
  'use strict';
  const JX = (globalThis.JX = globalThis.JX || {});
  const { $, el, esc, copyText, fmtTime } = JX.util;
  const S = JX.store;

  let list, scroller, toLatest;
  let stick = true;
  const raf = {}; // per-message render throttle

  const BADGE = {
    ai: (m) => ['badge-live', `LIVE · ${shortModel(m.meta && m.meta.model)}`],
    demo: () => ['badge-demo', 'DEMO · LOCAL RULES'],
    local: () => ['badge-local', 'LOCAL'],
    system: () => ['badge-sys', 'SYSTEM'],
    error: () => ['badge-err', 'ERROR'],
  };
  const shortModel = (m) => (m ? String(m).replace(/^claude-/, 'claude ').replace(/-\d{8}$/, '').slice(0, 24) : 'AI');
  const REGEN_PURE = ['random', 'password', 'time', 'date', 'calculate', 'convert', 'count', 'help', 'about', 'status'];
  const canRegen = (m) => m.role === 'assistant' && (['ai', 'demo', 'error'].includes(m.source) || (m.meta && m.meta.pure) || (m.meta && REGEN_PURE.includes(m.meta.cmd)));

  const isNear = () => scroller.scrollHeight - scroller.scrollTop - scroller.clientHeight < 140;

  function scroll(force, smooth) {
    if (!force && !stick) { updateToLatest(); return; }
    const behavior = smooth && JX.theme.effectiveAnim() !== 'off' ? 'smooth' : 'auto';
    requestAnimationFrame(() => { scroller.scrollTo({ top: scroller.scrollHeight, behavior }); stick = true; updateToLatest(); });
  }
  function updateToLatest() {
    const show = !isNear() && list.children.length > 0; toLatest.hidden = !show;
  }

  function contentHTML(msg, streaming) {
    if (msg.pending && !msg.content) return '<div class="typing" aria-label="JARVIX is thinking"><i></i><i></i><i></i></div>';
    if (msg.role === 'user') return JX.markdown.render(msg.content, { chips: false });
    return JX.markdown.render(msg.content, { chips: true, streaming });
  }

  function build(msg, conv, isLast) {
    const user = msg.role === 'user';
    const [bcls, btext] = !user && BADGE[msg.source] ? BADGE[msg.source](msg) : [null, null];
    const avatar = user ? el('div', { class: 'msg-avatar user-av', 'aria-hidden': 'true' }, (S.settings.name || 'You')[0].toUpperCase())
      : el('div', { class: 'msg-avatar ai-av', 'aria-hidden': 'true', html: JX.logo(26) });
    const bubble = el('div', { class: 'bubble md' + (msg.pending ? ' streaming' : ''), html: contentHTML(msg, msg.pending) });
    const meta = el('div', { class: 'msg-meta' },
      el('span', { class: 'msg-name' }, user ? (S.settings.name || 'You') : 'JARVIX'),
      btext ? el('span', { class: 'badge ' + bcls, title: msg.source === 'demo' ? 'Rule-based demo reply — not generated by an AI model' : msg.source === 'local' ? 'Computed locally in your browser' : msg.source === 'ai' ? `Generated by ${msg.meta && msg.meta.provider || 'AI'} (${msg.meta && msg.meta.model || ''})` : '' }, btext) : null,
      msg.ephemeral ? el('span', { class: 'badge badge-sys', title: 'Not saved to history and never sent to the AI' }, 'NOT SAVED') : null,
      msg.meta && msg.meta.stopped ? el('span', { class: 'badge badge-sys badge-stopped' }, 'STOPPED') : null,
      el('time', { class: 'msg-time', datetime: new Date(msg.ts).toISOString() }, fmtTime(msg.ts)));
    const routed = msg.meta && msg.meta.routed ? el('div', { class: 'msg-routed' }, 'Interpreted as ', el('code', {}, msg.meta.routed)) : null;
    const node = el('article', { class: `msg ${user ? 'msg-user' : 'msg-ai'}${msg.source === 'error' ? ' msg-error' : ''}`, 'data-id': msg.id, 'data-role': msg.role },
      avatar, el('div', { class: 'msg-body' }, meta, routed, bubble, actionsFor(msg, isLast)));
    return node;
  }

  function actionsFor(msg, isLast) {
    const wrap = el('div', { class: 'msg-actions' });
    if (msg.pending) return wrap;
    const add = (act, icon, label) => wrap.append(el('button', { type: 'button', class: 'act', 'data-act': act, 'aria-label': label, title: label, html: JX.icon(icon, 15) + `<span>${label}</span>` }));
    add('copy', 'copy', 'Copy');
    if (msg.role === 'assistant' && JX.voice.support().tts && !msg.ephemeral && msg.source !== 'error') add('speak', 'speaker', 'Speak');
    if (msg.role === 'user') add('edit', 'edit', 'Edit');
    if (isLast && canRegen(msg)) add('regen', 'refresh', msg.source === 'error' ? 'Retry' : 'Regenerate');
    return wrap;
  }

  function hydrate(root) {
    root.querySelectorAll('.fc-deck:not([data-ready])').forEach((d) => {
      d.dataset.ready = '1'; d._cards = JSON.parse(d.dataset.cards || '[]'); d._i = 0; showCard(d);
    });
    root.querySelectorAll('.codeblock.foldable').forEach((c) => { const b = c.querySelector('[data-fold]'); if (b && !b.dataset.set) { b.dataset.set = '1'; b.textContent = c.classList.contains('folded') ? 'Expand' : 'Collapse'; } });
  }
  function showCard(d) {
    const n = d._cards.length; d._i = (d._i + n) % n; const c = d._cards[d._i];
    d.querySelector('.fc-front').textContent = c[0]; d.querySelector('.fc-back').textContent = c[1];
    d.querySelector('.fc-card').classList.remove('flipped'); d.querySelector('.fc-count').textContent = `${d._i + 1} / ${n}`;
  }

  /** Collapse very tall finished replies behind a "Show more" fade. */
  function collapseIfLong(node) {
    const b = node.querySelector('.bubble'); if (!b || node.dataset.role !== 'assistant' || b.classList.contains('streaming')) return;
    if (b.scrollHeight <= 720 || b.querySelector('.typing, .qz, .fc-deck')) return; // never hide interactive quizzes / flashcards
    b.classList.add('collapsible', 'collapsed');
    if (!node.querySelector('.expand-btn')) b.after(el('button', { type: 'button', class: 'expand-btn', 'data-expand': '' }, 'Show full response'));
  }

  function finishNode(node) {
    hydrate(node);
    requestAnimationFrame(() => { collapseIfLong(node); });
  }

  const api = {
    init() {
      list = $('#messages'); scroller = $('#chatScroll'); toLatest = $('#toLatest');
      scroller.addEventListener('scroll', () => { stick = isNear(); updateToLatest(); }, { passive: true });
      toLatest.addEventListener('click', () => scroll(true, true));
      list.addEventListener('click', onClick);
      list.addEventListener('keydown', (e) => { const card = e.target.closest && e.target.closest('.fc-card'); if (card && (e.key === 'Enter' || e.key === ' ')) { e.preventDefault(); card.classList.toggle('flipped'); } });
    },

    renderAll(conv) {
      list.innerHTML = ''; stick = true;
      const msgs = conv ? conv.messages : [];
      msgs.forEach((m, i) => { const n = build(m, conv, i === msgs.length - 1); n.classList.add('no-anim'); list.append(n); finishNode(n); });
      api.syncWelcome(); if (msgs.length) scroll(true); else { scroller.scrollTop = 0; toLatest.hidden = true; }
    },

    /** Animated transition between conversations. */
    switchTo(conv) {
      if (JX.theme.effectiveAnim() === 'off') return api.renderAll(conv);
      list.classList.add('swap-out');
      setTimeout(() => { api.renderAll(conv); list.classList.remove('swap-out'); list.classList.add('swap-in'); setTimeout(() => list.classList.remove('swap-in'), 320); }, 130);
    },

    append(conv, msg) {
      // previous last message loses its regenerate button
      const prev = list.lastElementChild; if (prev) { const a = prev.querySelector('[data-act=regen]'); if (a && prev.dataset.id !== msg.id) a.remove(); }
      const n = build(msg, conv, true); list.append(n); finishNode(n); api.syncWelcome();
      scroll(msg.role === 'user', true); return n;
    },

    node: (id) => list.querySelector(`[data-id="${CSS.escape(id)}"]`),

    /** Re-render one message's body (throttled during streaming). */
    update(msg, { streaming } = {}) {
      if (streaming) { if (raf[msg.id]) return; raf[msg.id] = requestAnimationFrame(() => { delete raf[msg.id]; paint(msg, true); }); return; }
      cancelAnimationFrame(raf[msg.id]); delete raf[msg.id]; paint(msg, false);
    },

    remove(id) { const n = api.node(id); if (n) n.remove(); api.syncWelcome(); },

    syncWelcome() {
      const empty = list.children.length === 0;
      $('#welcome').hidden = !empty; list.hidden = empty;
      document.body.classList.toggle('is-empty-chat', empty);
    },
    scroll,
  };

  function paint(msg, streaming) {
    const n = api.node(msg.id); if (!n) return;
    const b = n.querySelector('.bubble');
    b.innerHTML = contentHTML(msg, streaming); b.classList.toggle('streaming', !!streaming && !!msg.content);
    if (!streaming) {
      b.classList.remove('streaming'); n.classList.toggle('msg-error', msg.source === 'error');
      const conv = S.active(); const body = n.querySelector('.msg-body');
      const old = body.querySelector('.msg-actions'); const fresh = actionsFor(msg, conv && conv.messages[conv.messages.length - 1] === msg);
      old ? old.replaceWith(fresh) : body.append(fresh);
      const meta = n.querySelector('.msg-meta'); const [bcls, btext] = BADGE[msg.source] ? BADGE[msg.source](msg) : [null, null];
      const badge = meta.querySelector('.badge'); if (badge && btext) { badge.className = 'badge ' + bcls; badge.textContent = btext; }
      else if (!badge && btext) meta.querySelector('.msg-name').after(el('span', { class: 'badge ' + bcls }, btext));
      if (msg.meta && msg.meta.stopped && !meta.querySelector('.badge-stopped')) meta.querySelector('.msg-name').after(el('span', { class: 'badge badge-sys badge-stopped' }, 'STOPPED'));
      finishNode(n);
    }
    scroll(false);
  }

  /* ---------- delegated clicks ---------- */
  async function onClick(e) {
    const t = e.target;
    let b;
    if ((b = t.closest('[data-copy-code]'))) {
      const cb = b.closest('.codeblock'); const text = [...cb.querySelectorAll('.ln')].map((s) => s.textContent.replace(/^ $/, '')).join('\n');
      const ok = await copyText(text); b.textContent = ok ? 'Copied ✓' : 'Copy failed'; b.classList.toggle('ok', ok); setTimeout(() => { b.textContent = 'Copy'; b.classList.remove('ok'); }, 1500); return;
    }
    if ((b = t.closest('[data-fold]'))) { const cb = b.closest('.codeblock'); cb.classList.toggle('folded'); b.textContent = cb.classList.contains('folded') ? 'Expand' : 'Collapse'; return; }
    if ((b = t.closest('.cmd-chip'))) { JX.composer.insertCommand(b.dataset.cmd); return; }
    if ((b = t.closest('[data-expand]'))) { const bubble = b.previousElementSibling; const open = bubble.classList.toggle('collapsed'); b.textContent = open ? 'Show full response' : 'Show less'; return; }
    if ((b = t.closest('.fc-card'))) { b.classList.toggle('flipped'); return; }
    if ((b = t.closest('[data-fc]'))) {
      const d = b.closest('.fc-deck'); const k = b.dataset.fc;
      if (k === 'next') d._i++; else if (k === 'prev') d._i--; else if (k === 'shuffle') { d._cards = JX.tools.shuffle(d._cards); d._i = 0; JX.ui.toast('Deck shuffled', 'info', { duration: 1200 }); }
      showCard(d); return;
    }
    if ((b = t.closest('.qz-opt'))) {
      const q = b.closest('.qz-q'); if (q.dataset.done) return; q.dataset.done = '1';
      const right = q.dataset.ans; const picked = b.dataset.k;
      q.querySelectorAll('.qz-opt').forEach((o) => { o.disabled = true; if (o.dataset.k === right) o.classList.add('right'); });
      if (picked !== right) b.classList.add('wrong'); else q.classList.add('got-it');
      const why = q.querySelector('.qz-why'); if (why.textContent.trim()) why.hidden = false;
      const quiz = q.closest('.qz'); const total = +quiz.dataset.total; const done = quiz.querySelectorAll('.qz-q[data-done]').length;
      if (done === total) { const score = quiz.querySelectorAll('.qz-q.got-it').length; const s = quiz.querySelector('.qz-score'); s.hidden = false; s.textContent = `Score: ${score} / ${total} — ${score === total ? 'perfect! 🎉' : score >= total * 0.7 ? 'nicely done.' : 'keep practising — try /study on this topic.'}`; JX.sound.play('done'); }
      return;
    }
    if ((b = t.closest('[data-act]'))) {
      const node = b.closest('.msg'); const conv = S.active(); const msg = conv && conv.messages.find((m) => m.id === node.dataset.id); if (!msg) return;
      const act = b.dataset.act;
      if (act === 'copy') { const ok = await copyText(msg.content); JX.ui.toast(ok ? 'Copied to clipboard' : 'Copy failed — select the text manually', ok ? 'success' : 'error', { duration: 1800 }); }
      else if (act === 'speak') { if (JX.voice.speaking) JX.voice.stopSpeaking(); else if (!(await JX.voice.speak(msg.content, { force: true }))) JX.ui.toast('Speech is not available in this browser', 'warn'); }
      else if (act === 'regen') JX.chat.regenerate(msg.id);
      else if (act === 'edit') JX.composer.setText(msg.content, true);
    }
  }

  JX.messages = api;
})();
